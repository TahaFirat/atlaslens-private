const apiBaseUrl = process.env.ATLASLENS_E2E_API_URL ?? "http://127.0.0.1:8100";
const apiProject = fileURLToPath(new URL("../../../services/api", import.meta.url));
const apiPython = process.env.ATLASLENS_E2E_PYTHON ?? resolve(
  apiProject,
  ".venv",
  process.platform === "win32" ? "Scripts/python.exe" : "bin/python",
);

function captureBrowserErrors(page: Page): string[] {
  const errors: string[] = [];
  page.on("console", (message) => {
    if (message.type() === "error") errors.push(message.text());
  });
  page.on("pageerror", (error) => errors.push(error.message));
  return errors;
}

function generateKnownExifFixture(): string {
  const output = fileURLToPath(new URL("../test-results/known-exif.jpg", import.meta.url));
  mkdirSync(fileURLToPath(new URL("../test-results", import.meta.url)), { recursive: true });
  const script = `
import sys
import piexif
from PIL import Image

def dms(value):
    absolute = abs(value)
    degrees = int(absolute)
    minutes_float = (absolute - degrees) * 60
    minutes = int(minutes_float)
    seconds = (minutes_float - minutes) * 60
    return ((degrees, 1), (minutes, 1), (round(seconds * 100000), 100000))

latitude = 41.0082
longitude = 28.9784
exif = {
    "0th": {piexif.ImageIFD.Orientation: 1},
    "GPS": {
        piexif.GPSIFD.GPSLatitudeRef: b"N",
        piexif.GPSIFD.GPSLatitude: dms(latitude),
        piexif.GPSIFD.GPSLongitudeRef: b"E",
        piexif.GPSIFD.GPSLongitude: dms(longitude),
        piexif.GPSIFD.GPSAltitudeRef: 0,
        piexif.GPSIFD.GPSAltitude: (125, 10),
    },
}
image = Image.new("RGB", (96, 72), (92, 118, 132))
image.save(sys.argv[1], "JPEG", quality=90, exif=piexif.dump(exif))
`;
  execFileSync(apiPython, ["-c", script, output], { cwd: apiProject, stdio: "pipe" });
  return output;
}

