test("known EXIF upload renders a real candidate and can be deleted", async ({ page, request }) => {
  const browserErrors = captureBrowserErrors(page);
  const fixture = generateKnownExifFixture();
  await page.goto("/");
  await expect(page.getByText("Analysis service available")).toBeVisible();

  await page.getByTestId("file-input").setInputFiles(fixture);
  await page.getByRole("checkbox", { name: /I own this image/ }).check();
  const createResponse = page.waitForResponse(
    (response) => response.request().method() === "POST" && new URL(response.url()).pathname === "/api/v1/analyses",
  );
  const analyze = page.getByRole("button", { name: "Analyze photo" });
  await expect(analyze).toBeEnabled();
  await analyze.click();
  const response = await createResponse;
  expect(response.status()).toBe(202);
  const accepted = (await response.json()) as { id: string };

  await expect(page.getByRole("heading", { name: "Candidate regions" })).toBeVisible({ timeout: 20_000 });
  await expect(page.getByRole("heading", { name: "Candidate 1" })).toBeVisible();
  await expect(page.getByText("Source-derived support").first()).toBeVisible();
  await expect(page.getByTestId("map-region")).toBeVisible();
  await expect(page.getByRole("heading", { name: "Textual map alternative" })).toBeVisible();

  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);

  await page.getByRole("button", { name: "Delete analysis" }).click();
  await expect(page.getByText("Analysis deleted from the server.")).toBeVisible();
  await expect(page.getByRole("heading", { name: "Candidate 1" })).toHaveCount(0);
  const deleted = await request.get(`${apiBaseUrl}/api/v1/analyses/${accepted.id}`);
  expect(deleted.status()).toBe(404);
  expect(browserErrors).toEqual([]);
});

