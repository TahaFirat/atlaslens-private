export type Locale = "en" | "tr";
type Params = Record<string, string | number>;

function browserLocale(): Locale {
  if (typeof navigator === "undefined") return "en";
  return navigator.languages.some((language) => language.toLocaleLowerCase().startsWith("tr")) ? "tr" : "en";
}

function interpolate(message: string, params?: Params): string {
  if (!params) return message;
  return Object.entries(params).reduce(
    (value, [key, replacement]) => value.replaceAll(`{${key}}`, String(replacement)),
    message,
  );
}

interface I18nValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey, params?: Params) => string;
  serverMessage: (code: string | null | undefined) => string;
  reasonMessage: (code: string | null | undefined) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children, initialLocale }: { children: ReactNode; initialLocale?: Locale }) {
  const [locale, setLocale] = useState<Locale>(initialLocale ?? browserLocale);
  const value = useMemo<I18nValue>(() => {
    const dictionary = locale === "tr" ? tr : en;
    const t = (key: TranslationKey, params?: Params) => interpolate(dictionary[key], params);
    return {
      locale,
      setLocale,
      t,
      serverMessage(code) {
        if (!code) return t("errors.unknown");
        const suffix = code.replace(/^errors?\./, "");
        const normalized = `errors.${suffix}`;
        return normalized in dictionary
          ? t(normalized as TranslationKey)
          : t("server.unknown", { code: code.replaceAll(/[^a-zA-Z0-9_.-]/g, "") || "unknown" });
      },
      reasonMessage(code) {
        if (!code) return t("reason.unknown");
        const normalized = code.startsWith("reason.") ? code : `reason.${code}`;
        return normalized in dictionary ? t(normalized as TranslationKey) : t("reason.unknown");
      },
    };
  }, [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}
